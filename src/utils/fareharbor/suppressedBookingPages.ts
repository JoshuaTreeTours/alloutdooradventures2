export const RETIRED_FAREHARBOR_TOURS = SUPPRESSED_FAREHARBOR_BOOKING_PAGES;

const suppressedByProviderAndItem = new Set(
  SUPPRESSED_FAREHARBOR_BOOKING_PAGES.map(
    row => `${row.provider}:${row.itemId}`
  )
);

export const RETIRED_FAREHARBOR_TOUR_IDS = new Set(
  SUPPRESSED_FAREHARBOR_BOOKING_PAGES.map(row => row.itemId)
);

export const RETIRED_FAREHARBOR_TOUR_URLS = new Set(
  SUPPRESSED_FAREHARBOR_BOOKING_PAGES.map(row => row.tourUrl)
);

export const RETIRED_FAREHARBOR_BOOKING_URLS = new Set(
  SUPPRESSED_FAREHARBOR_BOOKING_PAGES.map(row => row.bookingPageUrl)
);

export const getRetiredFareHarborTourRedirectPath = (args: {
  stateSlug: string;
  citySlug: string;
  tourSlug: string;
}) => {
  const tourPath = `/destinations/${args.stateSlug}/${args.citySlug}/tours/${args.tourSlug}`;
  const isRetired = RETIRED_FAREHARBOR_TOUR_URLS.has(tourPath);

  return isRetired
    ? `/destinations/${args.stateSlug}/${args.citySlug}/tours`
    : null;
};

export const getFareHarborProviderAndItem = (url?: string) => {
  const match = url?.match(
    /fareharbor\.com\/embeds\/(?:book|calendar)\/([^/]+)\/items\/(\d+)/
  );
  if (!match) return null;
  return { provider: match[1], itemId: match[2] };
};

type FareHarborBookingCandidate = {
  bookingProvider?: string;
  bookingUrl?: string;
  bookingWidgetUrl?: string;
  booking?: {
    bookingUrl?: string;
    fareharbor?: {
      shortname?: string;
      itemId?: string;
    };
  };
};

const getCandidateMapping = (tour: FareHarborBookingCandidate) => {
  const engine2Mapping = tour.booking?.fareharbor;
  if (engine2Mapping?.shortname && engine2Mapping.itemId) {
    return {
      provider: engine2Mapping.shortname,
      itemId: engine2Mapping.itemId,
    };
  }

  return getFareHarborProviderAndItem(
    tour.bookingWidgetUrl || tour.bookingUrl || tour.booking?.bookingUrl
  );
};

export const isSuppressedFareHarborBookingPage = (
  tour?: FareHarborBookingCandidate | null
) => {
  if (!tour || tour.bookingProvider !== "fareharbor") return false;
  const mapping = getCandidateMapping(tour);
  return Boolean(
    mapping &&
    suppressedByProviderAndItem.has(`${mapping.provider}:${mapping.itemId}`)
  );
};

export const getSuppressedFareHarborBookingPage = (
  tour?: FareHarborBookingCandidate | null
) => {
  if (!tour || tour.bookingProvider !== "fareharbor") return null;
  const mapping = getCandidateMapping(tour);
  if (!mapping) return null;
  return (
    SUPPRESSED_FAREHARBOR_BOOKING_PAGES.find(
      row => row.provider === mapping.provider && row.itemId === mapping.itemId
    ) ?? null
  );
};
