const buildPoiIndex = () => {
  const index = new Map<string, CityPoi[]>();
  tier1CityPois.forEach((poi) => {
    const key = `${poi.state}/${poi.citySlug}`;
    const list = index.get(key) ?? [];
    list.push(poi);
    index.set(key, list);
  });

  return index;
};

let poiIndex: Map<string, CityPoi[]> | null = null;

export const getTier1PoisForCity = (parentSlug: string, citySlug: string) => {
  if (!poiIndex) {
    poiIndex = buildPoiIndex();
  }

  return poiIndex.get(`${parentSlug}/${citySlug}`) ?? [];
};

export const getTier1PoiNameSet = (parentSlug: string, citySlug: string) =>
  new Set(
    getTier1PoisForCity(parentSlug, citySlug).map((poi) =>
      normalizePlaceName(poi.name),
    ),
  );
