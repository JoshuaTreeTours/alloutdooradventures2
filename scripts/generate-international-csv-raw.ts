import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";

type SourceFile = {
  exportName: string;
  relativeCsvPath: string;
};

const sourceFiles: SourceFile[] = [
  { exportName: "amsterdamCsvRaw", relativeCsvPath: "data/amsterdam.csv" },
  { exportName: "caboCsvRaw", relativeCsvPath: "data/cabo.csv" },
  { exportName: "cancunCsvRaw", relativeCsvPath: "data/cancun.csv" },
  { exportName: "mexicoCsvRaw", relativeCsvPath: "data/mexico.csv" },
  { exportName: "mexicoCityCsvRaw", relativeCsvPath: "data/mexico city.csv" },
  { exportName: "puertoVallartaCsvRaw", relativeCsvPath: "data/Puerto Vallarta.csv" },
  { exportName: "spainCsvRaw", relativeCsvPath: "data/spain.csv" },
  { exportName: "hawaiiCsvRaw", relativeCsvPath: "data/hawaii.csv" },
];

const outputPath = resolve("src/data/international/generatedCsvRaw.ts");

const loadRawCsv = (relativeCsvPath: string) => {
  try {
    return readFileSync(resolve(relativeCsvPath), "utf8");
  } catch {
    return "";
  }
};

const lines: string[] = [
  "/* eslint-disable */",
  "// AUTO-GENERATED by scripts/generate-international-csv-raw.ts",
  "// Do not edit manually.",
  "",
];

for (const sourceFile of sourceFiles) {
  const rawCsv = loadRawCsv(sourceFile.relativeCsvPath);
  lines.push(
    `export const ${sourceFile.exportName} = ${JSON.stringify(rawCsv)};`,
  );
}

lines.push("");

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, lines.join("\n"));

console.log(`Generated ${outputPath}`);
