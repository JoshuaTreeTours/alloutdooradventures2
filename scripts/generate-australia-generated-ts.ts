import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const INPUT_PATH = path.resolve("data/australia.csv");
const OUTPUT_PATH = path.resolve("src/data/generated/australia.generated.ts");

const escapeTemplateLiteral = (value: string) =>
  value.replace(/`/g, "\\`").replace(/\$\{/g, "\\${");

const generate = async () => {
  const csvContents = await readFile(INPUT_PATH, "utf8");
  const escaped = escapeTemplateLiteral(csvContents);
  const output = `// This file is auto-generated by scripts/generate-australia-generated-ts.ts. Do not edit manually.

export const australiaCsv = \`${escaped}\`;
`;

  await writeFile(OUTPUT_PATH, output, "utf8");
};

generate().catch((error) => {
  console.error("[generate-australia-generated-ts] Failed to generate:", error);
  process.exitCode = 1;
});
