{
 const p=path.join(root,"src/engine2/pages/Engine2TourPage.tsx"); let s=await readFile(p,"utf8");
 s=s.replace("const showFallbackPrice = !overridePriceLabel && !enginePriceLabel;","const showFallbackPrice = isViatorTour && !overridePriceLabel && !enginePriceLabel;");
 s=s.replace(/\{showFallbackPrice \? \([\s\S]*?From \$129 per person[\s\S]*?\) : null\}/m,"{showFallbackPrice ? (\n            <p className=\"mt-4 text-sm font-semibold text-white/90\">Price shown by booking provider</p>\n          ) : null}");
 s=s.replace(/\) : bookingPath \? \(\s*<Link href=\{bookingPath\}>[\s\S]*?<\/Link>\s*\) : null\}/m,`) : bookingPath ? (\n              <a href={tour.bookingUrl ?? tour.booking.bookingUrl} target=\"_blank\" rel={EXTERNAL_CTA_REL} className=\"inline-flex items-center justify-center rounded-md bg-[#2f8a3d] px-4 py-2 text-sm font-semibold text-white transition hover:bg-[#287a35]\">Learn More</a>\n            ) : null}`);
 await writeFile(p,s,"utf8");
}

